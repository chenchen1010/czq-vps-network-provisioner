#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

function argValue(name, fallback = undefined) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1];
}

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(2);
}

const envPath = argValue("--env");
const uriFile = argValue("--uri-file");
const outputPath = argValue("--out");
const testMode = process.argv.includes("--test");
const subscriptionTemplate = process.argv.includes("--subscription-template");
const mixedPort = Number(argValue("--mixed-port", testMode ? "17900" : "7897"));

if (subscriptionTemplate && (envPath || uriFile || testMode)) {
  fail("--subscription-template does not accept --env, --uri-file, or --test");
}
if (!subscriptionTemplate && ((!envPath && !uriFile) || (envPath && uriFile))) {
  fail("provide exactly one of --env or --uri-file");
}
if (!outputPath) fail("missing --out");
if (!Number.isInteger(mixedPort) || mixedPort < 1024 || mixedPort > 65535) {
  fail("--mixed-port must be an integer from 1024 to 65535");
}

let uuid, server, port, publicKey, shortId, serverName, fingerprint, flow, label;
if (!subscriptionTemplate) {
  let shareLink;
  if (envPath) {
    const lines = fs.readFileSync(envPath, "utf8").split(/\r?\n/);
    const line = lines.find((item) => item.startsWith("VLESS_SHARE_LINK="));
    if (!line) fail("VLESS_SHARE_LINK is missing from env file");
    shareLink = line.slice("VLESS_SHARE_LINK=".length).trim();
  } else {
    shareLink = fs.readFileSync(uriFile, "utf8").trim();
  }

  let uri;
  try {
    uri = new URL(shareLink);
  } catch {
    fail("invalid VLESS URI");
  }

  if (uri.protocol !== "vless:") fail("URI protocol must be vless://");
  uuid = decodeURIComponent(uri.username);
  server = uri.hostname;
  port = Number(uri.port);
  const security = uri.searchParams.get("security");
  publicKey = uri.searchParams.get("pbk") || uri.searchParams.get("password");
  shortId = uri.searchParams.get("sid") || "";
  serverName = uri.searchParams.get("sni") || "";
  fingerprint = uri.searchParams.get("fp") || "chrome";
  flow = uri.searchParams.get("flow") || "xtls-rprx-vision";
  const transport = uri.searchParams.get("type") || "tcp";
  label = decodeURIComponent(uri.hash.replace(/^#/, "")) || "VPS-Reality";

  if (!uuid || !server || !Number.isInteger(port) || port < 1 || port > 65535) {
    fail("VLESS URI is missing UUID, server, or port");
  }
  if (security !== "reality") fail("only Reality links are supported");
  if (!publicKey || !serverName) fail("Reality public key or SNI is missing");
  if (!/^[0-9a-f]*$/i.test(shortId) || shortId.length % 2 !== 0 || shortId.length > 16) {
    fail("Reality short ID must be even-length hexadecimal, up to 16 characters");
  }
  if (!new Set(["tcp", "raw"]).has(transport)) {
    fail("only TCP/RAW Reality links are supported");
  }

}

